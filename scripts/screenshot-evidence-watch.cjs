#!/usr/bin/env node

"use strict";

const { spawnSync } = require("node:child_process");

const SCREENSHOT_NEEDED_LABEL = "screenshot needed";
const SCREENSHOT_PR_LABEL = "screenshot";
const STATUS_CONTEXT = "Screenshot Evidence";
const MARKER = "excalidash-screenshot-evidence:v1";
const PACKAGE_PATTERN = /^Multica-Package:\s*(NIL-[1-9][0-9]*)\s*$/gim;
const RAW_EVIDENCE_PATTERN =
  /^https:\/\/raw\.githubusercontent\.com\/davifernan\/excalidash\/evidence\/.+\.(?:png|jpe?g|webp|gif)(?:\?.*)?$/i;

const labelNames = (labels) =>
  (labels || []).map((label) => (typeof label === "string" ? label : label?.name)).filter(Boolean);

function primaryPackage(body) {
  const matches = [...String(body || "").matchAll(PACKAGE_PATTERN)].map((match) =>
    match[1].toUpperCase(),
  );
  return matches.length === 1 ? matches[0] : null;
}

function imageUrls(text) {
  const source = String(text || "");
  const urls = [];
  for (const match of source.matchAll(/!\[[^\]]*\]\((https?:\/\/[^\s)]+)(?:\s+[^)]*)?\)/gi)) {
    urls.push(match[1]);
  }
  for (const match of source.matchAll(/<img\b[^>]*\bsrc=["'](https?:\/\/[^"']+)["'][^>]*>/gi)) {
    urls.push(match[1]);
  }
  return [...new Set(urls)];
}

function classifyScreenshotEvidence({ issue, pr, comments = [] }) {
  if (!issue) return { result: "ambiguous", reason: "multica-issue-unavailable" };
  if (!labelNames(issue.labels).includes(SCREENSHOT_NEEDED_LABEL)) {
    return { result: "not-required", reason: "ticket-label-absent" };
  }
  if (!pr) return { result: "ambiguous", reason: "linked-pr-unavailable" };
  if (primaryPackage(pr.body) !== String(issue.identifier).toUpperCase()) {
    return { result: "ambiguous", reason: "package-link-not-unique" };
  }
  if (pr.isDraft) return { result: "pending", reason: "draft" };

  const urls = imageUrls([pr.body, ...comments.map((comment) => comment.body)].join("\n"));
  const supportedUrls = urls.filter((url) => RAW_EVIDENCE_PATTERN.test(url));
  if (supportedUrls.length > 0) return { result: "satisfied", supportedUrls };
  if (urls.length > 0) return { result: "ambiguous", reason: "unrecognized-image-location", urls };
  return { result: "missing", reason: "no-image-reference" };
}

function signalMarker(headSha, kind, reason) {
  return `<!-- ${MARKER} head=${headSha} kind=${kind} reason=${reason} -->`;
}

function ambiguousComment({ pr, issue, reason }) {
  return `${signalMarker(pr.headRefOid, "ambiguous", reason)}
Screenshot Evidence konnte für **${issue.identifier}** nicht sicher bewertet werden.

PR: ${pr.url}
Grund: \`${reason}\`

Es wird bewusst **kein roter Status** gesetzt. Bitte den Bildnachweis auf dem dauerhaften
\`evidence\`-Branch ablegen, im PR per Raw-URL einbinden und den PR mit \`screenshot\` labeln.

Generated by Screenshot Evidence Watcher`;
}

function missingComment({ pr, issue, reason }) {
  const detail =
    reason === "evidence-url-not-an-image"
      ? `Der verlinkte Nachweis vom \`evidence\`-Branch antwortet nicht mit einem abrufbaren Bild.`
      : `Das Multica-Ticket trägt \`${SCREENSHOT_NEEDED_LABEL}\`, aber PR #${pr.number} enthält weder im
Text noch in seinen Kommentaren einen Bildnachweis.`;
  return `${signalMarker(pr.headRefOid, "missing", reason)}
Screenshot Evidence fehlt für **${issue.identifier}**.

${detail} Der Status \`${STATUS_CONTEXT}\` bleibt rot,
bis eine Raw-URL vom dauerhaften \`evidence\`-Branch eingebunden ist.

Generated by Screenshot Evidence Watcher`;
}

function commandJson(command, args, { allowFailure = false } = {}) {
  const result = spawnSync(command, args, {
    encoding: "utf8",
    env: process.env,
    maxBuffer: 16 * 1024 * 1024,
  });
  if (result.status !== 0) {
    if (allowFailure) return null;
    throw new Error(`${command} ${args.slice(0, 3).join(" ")} failed`);
  }
  return JSON.parse(result.stdout);
}

function createLiveAdapter(repository) {
  return {
    listOpenPrs: () =>
      commandJson("gh", [
        "pr",
        "list",
        "--repo",
        repository,
        "--state",
        "open",
        "--limit",
        "100",
        "--json",
        "number,isDraft,body,headRefOid,url,labels",
      ]),
    getIssue: (identifier) =>
      commandJson("multica", ["issue", "get", identifier, "--output", "json"], {
        allowFailure: true,
      }),
    getComments: (number) =>
      commandJson("gh", [
        "api",
        `repos/${repository}/issues/${number}/comments`,
        "--paginate",
        "--slurp",
      ]).flat(),
    setStatus: (sha, state, description) =>
      commandJson("gh", [
        "api",
        "--method",
        "POST",
        `repos/${repository}/statuses/${sha}`,
        "-f",
        `state=${state}`,
        "-f",
        `context=${STATUS_CONTEXT}`,
        "-f",
        `description=${description.slice(0, 140)}`,
      ]),
    addLabel: (number) =>
      commandJson("gh", [
        "api",
        "--method",
        "POST",
        `repos/${repository}/issues/${number}/labels`,
        "-f",
        `labels[]=${SCREENSHOT_PR_LABEL}`,
      ]),
    comment: (number, body) =>
      commandJson("gh", [
        "api",
        "--method",
        "POST",
        `repos/${repository}/issues/${number}/comments`,
        "-f",
        `body=${body}`,
      ]),
  };
}

const hasMarker = (comments, marker) =>
  comments.some((comment) => String(comment.body || "").includes(marker));

async function verifyUrls(urls, fetchImpl = fetch) {
  const outcomes = [];
  for (const url of urls) {
    try {
      const response = await fetchImpl(url, { signal: AbortSignal.timeout(10_000) });
      const contentType = String(response.headers.get("content-type") || "");
      const definitelyMissing = response.status === 404 || response.status === 410;
      outcomes.push({
        url,
        ok: response.ok ? contentType.startsWith("image/") : definitelyMissing ? false : null,
        status: response.status,
      });
    } catch (error) {
      outcomes.push({ url, ok: null, error: error.message });
    }
  }
  return outcomes;
}

async function inspectPr({ adapter, pr, fetchImpl = fetch }) {
  const identifier = primaryPackage(pr.body);
  if (!identifier) return { pr: pr.number, result: "ambiguous", reason: "package-link-not-unique" };
  const issue = adapter.getIssue(identifier);
  if (!issue)
    return {
      pr: pr.number,
      issue: identifier,
      result: "ambiguous",
      reason: "multica-issue-unavailable",
    };

  let comments;
  try {
    comments = adapter.getComments(pr.number);
  } catch {
    return {
      pr: pr.number,
      issue: identifier,
      result: "ambiguous",
      reason: "pr-comments-unavailable",
    };
  }
  const classification = classifyScreenshotEvidence({ issue, pr, comments });

  if (classification.result === "satisfied") {
    const verified = await verifyUrls(classification.supportedUrls, fetchImpl);
    if (verified.some((outcome) => outcome.ok === null)) {
      classification.result = "ambiguous";
      classification.reason = "evidence-url-unreachable";
    } else if (!verified.every((outcome) => outcome.ok)) {
      classification.result = "missing";
      classification.reason = "evidence-url-not-an-image";
    } else {
      if (!labelNames(pr.labels).includes(SCREENSHOT_PR_LABEL)) adapter.addLabel(pr.number);
      adapter.setStatus(pr.headRefOid, "success", `${identifier}: durable image evidence verified`);
      return { pr: pr.number, issue: identifier, result: "satisfied", urls: verified.length };
    }
  }

  if (classification.result === "missing") {
    adapter.setStatus(
      pr.headRefOid,
      "failure",
      `${identifier}: required image evidence is missing`,
    );
    const marker = signalMarker(pr.headRefOid, "missing", classification.reason);
    if (!hasMarker(comments, marker)) {
      adapter.comment(pr.number, missingComment({ pr, issue, reason: classification.reason }));
    }
    return { pr: pr.number, issue: identifier, ...classification };
  }

  if (classification.result === "ambiguous") {
    const marker = signalMarker(pr.headRefOid, "ambiguous", classification.reason);
    if (!hasMarker(comments, marker)) {
      adapter.comment(pr.number, ambiguousComment({ pr, issue, reason: classification.reason }));
    }
  }
  return { pr: pr.number, issue: identifier, ...classification };
}

async function runWatch({ adapter, fetchImpl = fetch }) {
  const events = [];
  for (const pr of adapter.listOpenPrs()) events.push(await inspectPr({ adapter, pr, fetchImpl }));
  return { ok: true, checkedAt: new Date().toISOString(), events };
}

module.exports = {
  RAW_EVIDENCE_PATTERN,
  SCREENSHOT_NEEDED_LABEL,
  SCREENSHOT_PR_LABEL,
  STATUS_CONTEXT,
  ambiguousComment,
  classifyScreenshotEvidence,
  imageUrls,
  inspectPr,
  missingComment,
  primaryPackage,
  runWatch,
  signalMarker,
  verifyUrls,
};

if (require.main === module) {
  const repository = process.env.SCREENSHOT_EVIDENCE_REPOSITORY || "davifernan/excalidash";
  runWatch({ adapter: createLiveAdapter(repository) })
    .then((result) => process.stdout.write(`${JSON.stringify(result)}\n`))
    .catch((error) => {
      process.stderr.write(`${error.message}\n`);
      process.exitCode = 1;
    });
}
