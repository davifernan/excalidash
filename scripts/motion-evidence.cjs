#!/usr/bin/env node

"use strict";

const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const MAX_DURATION_SECONDS = 12;
const MAX_BYTES = 5 * 1024 * 1024;
const GIF_WIDTH = 640;
const GIF_FPS = 8;
const PACKAGE_PATTERN = /^NIL-[1-9][0-9]*$/;
const NAME_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const NILO_IDENTITY = "Nilo <127136134+davifernan@users.noreply.github.com>";

function command(command, args, options = {}) {
  return execFileSync(command, args, { encoding: "utf8", stdio: "pipe", ...options });
}

function parseOptions(args) {
  const result = {};
  for (let index = 0; index < args.length; index += 1) {
    const option = args[index];
    if (!option.startsWith("--")) throw new Error(`Unexpected argument: ${option}`);
    const value = args[index + 1];
    if (!value || value.startsWith("--")) throw new Error(`Missing value for ${option}`);
    result[option.slice(2)] = value;
    index += 1;
  }
  return result;
}

function validatePublication({ packageId, name }) {
  if (!PACKAGE_PATTERN.test(packageId || "")) throw new Error("--package must be a NIL-NNN identifier.");
  if (!NAME_PATTERN.test(name || "")) {
    throw new Error("--name must use lowercase letters, numbers, and single hyphens.");
  }
}

function rawEvidenceUrl(packageId, filename) {
  return `https://raw.githubusercontent.com/davifernan/excalidash/evidence/motion/${packageId}/${filename}`;
}

function gifFilename(name) {
  return `${name}.gif`;
}

function assertNiloIdentity(cwd) {
  for (const variable of ["GIT_AUTHOR_IDENT", "GIT_COMMITTER_IDENT"]) {
    if (!command("git", ["var", variable], { cwd }).startsWith(NILO_IDENTITY)) {
      throw new Error(`Evidence commit refused: ${variable} is not ${NILO_IDENTITY}.`);
    }
  }
}

function convert(input, output) {
  if (!fs.statSync(input).isFile()) throw new Error(`Video does not exist: ${input}`);
  fs.mkdirSync(path.dirname(output), { recursive: true });
  command("ffmpeg", [
    "-y",
    "-i", input,
    "-t", String(MAX_DURATION_SECONDS),
    "-vf", `fps=${GIF_FPS},scale=${GIF_WIDTH}:-2:flags=lanczos`,
    "-loop", "0",
    output,
  ]);
  const bytes = fs.statSync(output).size;
  if (bytes > MAX_BYTES) {
    fs.rmSync(output, { force: true });
    throw new Error(`GIF is ${bytes} bytes; the ${MAX_BYTES}-byte evidence limit rejected it.`);
  }
  return { output, bytes, maxDurationSeconds: MAX_DURATION_SECONDS, width: GIF_WIDTH, fps: GIF_FPS };
}

function publish({ packageId, pr, input, name }) {
  validatePublication({ packageId, name });
  if (!/^\d+$/.test(pr || "")) throw new Error("--pr must be a pull-request number.");
  const root = command("git", ["rev-parse", "--show-toplevel"]).trim();
  const filename = gifFilename(name);
  const worktree = fs.mkdtempSync(path.join(os.tmpdir(), "excalidash-motion-evidence-"));
  const destination = path.join(worktree, "motion", packageId, filename);
  try {
    command("git", ["fetch", "fork", "evidence"], { cwd: root });
    command("git", ["worktree", "add", "--detach", worktree, "fork/evidence"], { cwd: root });
    if (fs.existsSync(destination)) throw new Error(`Evidence path already exists: motion/${packageId}/${filename}`);
    const result = convert(input, destination);
    command("git", ["add", "--", path.relative(worktree, destination)], { cwd: worktree });
    assertNiloIdentity(worktree);
    command("git", ["commit", "-m", `evidence: add ${packageId} ${name} motion proof\n\nGenerated by Nilo`], {
      cwd: worktree,
    });
    const commitIdentity = command("git", ["show", "-s", "--format=author=%an <%ae>%ncommitter=%cn <%ce>", "HEAD"], {
      cwd: worktree,
    });
    if (commitIdentity !== `author=${NILO_IDENTITY}\ncommitter=${NILO_IDENTITY}\n`) {
      throw new Error("Evidence commit identity verification failed.");
    }
    command("git", ["push", "fork", "HEAD:refs/heads/evidence"], { cwd: worktree });
    const url = rawEvidenceUrl(packageId, filename);
    command("gh", ["pr", "comment", pr, "--repo", "davifernan/excalidash", "--body", `Motion evidence (${packageId}, focused green Playwright run):\n\n![${name}](${url})\n\n12s maximum, 640px wide, 8fps, ${result.bytes} bytes.`], { cwd: root });
    command("gh", ["pr", "edit", pr, "--repo", "davifernan/excalidash", "--add-label", "screenshot"], { cwd: root });
    return { ...result, url, filename };
  } finally {
    try {
      command("git", ["worktree", "remove", "--force", worktree], { cwd: root });
    } catch {
      fs.rmSync(worktree, { recursive: true, force: true });
    }
  }
}

function main(argv) {
  const [action, ...args] = argv;
  const options = parseOptions(args);
  if (action === "convert") {
    if (!options.input || !options.output) throw new Error("convert requires --input and --output.");
    return convert(options.input, options.output);
  }
  if (action === "publish") {
    if (!options.package || !options.pr || !options.input || !options.name) {
      throw new Error("publish requires --package, --pr, --input, and --name.");
    }
    return publish({ packageId: options.package, pr: options.pr, input: options.input, name: options.name });
  }
  throw new Error("Usage: motion-evidence.cjs convert --input VIDEO --output GIF | publish --package NIL-NNN --pr NUMBER --input VIDEO --name slug");
}

if (require.main === module) {
  try {
    process.stdout.write(`${JSON.stringify(main(process.argv.slice(2)))}\n`);
  } catch (error) {
    process.stderr.write(`motion-evidence: ${error.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = {
  GIF_FPS,
  GIF_WIDTH,
  MAX_BYTES,
  MAX_DURATION_SECONDS,
  convert,
  gifFilename,
  parseOptions,
  rawEvidenceUrl,
  assertNiloIdentity,
  validatePublication,
};
